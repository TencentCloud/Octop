#!/usr/bin/env bash
# 去掉本地版 FPK 里用不到的大体量文件：
#   - googleapiclient 离线 discovery 缓存（联网时再拉）
#   - __pycache__ / *.pyc
# 必须保留 playwright/driver（自带 node 与 JS）。控制台「安装浏览器」
# 和安装后的驱动都依赖它；删掉后 playwright install 还没开始下载就会失败。
# Chromium 本体不在这个目录里，仍然按需下载。
# 用法：bash scripts/fnos/slim-site-packages.sh /path/to/site-packages
set -euo pipefail

SP="${1:-}"
[ -n "$SP" ] && [ -d "$SP" ] || {
  echo "用法: $0 <site-packages 目录>" >&2
  exit 1
}

rm -rf "${SP}/googleapiclient/discovery_cache"

find "$SP" -depth -type d -name '__pycache__' -exec rm -rf {} +
find "$SP" -type f \( -name '*.pyc' -o -name '*.pyo' \) -delete

echo "[slim-site-packages] 已精简: $SP"
