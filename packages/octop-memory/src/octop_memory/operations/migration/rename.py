"""``memory migrate --rename-namespace`` (5.3) — SQL-level table rename.

Operates **directly on the SQLite database file** because renaming a
namespace is purely a metadata operation: every table in our schema
is named ``{namespace}_{suffix}``, so we just iterate
``sqlite_master`` for tables matching the old prefix and emit
``ALTER TABLE old_name RENAME TO new_name`` per row.

Supports two modes:

- **rename** (default): atomically renames all tables in a single
  transaction. The source namespace ceases to exist after this.
- **copy** (``--keep-source``): copies every row to a new set of tables
  under the new namespace, leaves the source intact. Useful for
  side-by-side testing while migrating between namespaces.

D49-C: callers can do a ``--dry-run`` via :mod:`migration.preview`,
which calls :func:`plan_rename` and renders either a terminal table
or JSON. Live execution is :func:`apply_rename`.

NB: SQLite FTS5 virtual tables (``{ns}_atoms_fts``, etc.) **can** be
renamed by ``ALTER TABLE`` in modern SQLite (3.25+). The triggers that
keep them in sync are auto-recreated by the ``_init_schema`` of the
new ``Memory`` instance opened against the renamed namespace, so the
caller is encouraged to instantiate a fresh ``Memory`` after rename.
"""

from __future__ import annotations

import sqlite3
from dataclasses import dataclass, field
from pathlib import Path
from typing import Literal

from octop_memory.storage.backends.fts_text import register_fts_functions

RenameMode = Literal["rename", "copy"]


@dataclass
class TablePlan:
    """One step in a rename plan."""

    src_table: str
    dst_table: str
    row_count: int
    """Best-effort count for diagnostics (``COUNT(*)`` on the source).
    Skipped (-1) for FTS shadow tables which can be expensive to count."""

    is_fts_shadow: bool = False
    """``True`` for FTS5 virtual tables and their internal shadow tables
    (``_data``, ``_idx``, ``_docsize``, ``_content``, ``_config``).
    Renamed via ``ALTER TABLE`` like any other table; flagged so the
    CLI can group them in the dry-run output."""


@dataclass
class RenamePlan:
    """Full rename / copy plan, generated by :func:`plan_rename`.

    ``conflicts`` lists destination table names that already exist —
    the operation is **refused** unless the caller passes
    ``allow_overwrite=True`` (which deletes the conflicting destination
    first).
    """

    db_path: Path
    src_namespace: str
    dst_namespace: str
    mode: RenameMode
    steps: list[TablePlan] = field(default_factory=list)
    conflicts: list[str] = field(default_factory=list)

    @property
    def total_rows(self) -> int:
        return sum(s.row_count for s in self.steps if s.row_count >= 0)

    @property
    def has_conflicts(self) -> bool:
        return bool(self.conflicts)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


# FTS5 maintains internal "shadow" tables with these suffixes; they are
# auto-managed by the parent virtual table. Renaming the virtual table
# cascades to its shadows automatically, so listing them as separate
# rename steps would actually fail (SQLite refuses to ALTER shadow
# tables directly). We filter them out from the planning phase.
_FTS_SHADOW_TAIL = ("_fts_data", "_fts_idx", "_fts_docsize", "_fts_content", "_fts_config")


def _is_fts_shadow(table: str) -> bool:
    """``True`` if ``table`` is an FTS5 internal shadow (skip during rename)."""
    return any(table.endswith(suffix) for suffix in _FTS_SHADOW_TAIL)


def _is_fts_virtual(table: str) -> bool:
    """Whether ``table`` is the FTS5 virtual table itself.

    ``True`` if ``table`` is the FTS5 virtual table itself (the one
    with a non-shadow ``_fts`` suffix). Renaming this **does** cascade
    to all shadows, so we DO include it in the plan."""
    if _is_fts_shadow(table):
        return False
    return table.endswith("_fts")


def _list_namespace_tables(conn: sqlite3.Connection, namespace: str) -> list[str]:
    """Return every user-table name beginning with ``{namespace}_``.

    We use the literal escape so a namespace containing ``_`` doesn't
    over-match (SQLite ``LIKE`` treats ``_`` as a wildcard by default).
    """
    escaped = namespace.replace("_", "\\_")
    pattern = escaped + "\\_%"
    rows = conn.execute(
        "SELECT name FROM sqlite_master WHERE type IN ('table')   AND name LIKE ? ESCAPE '\\' ORDER BY name",
        (pattern,),
    ).fetchall()
    return [r[0] for r in rows]


def _table_row_count(conn: sqlite3.Connection, table: str) -> int:
    """``COUNT(*)`` for ``table``, ``-1`` on error (e.g. FTS internals)."""
    try:
        cur = conn.execute(f'SELECT COUNT(*) FROM "{table}"')
        return int(cur.fetchone()[0])
    except sqlite3.Error:
        return -1


