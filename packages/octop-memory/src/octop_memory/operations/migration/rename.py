def _collect_fts_tables(conn: sqlite3.Connection, namespace: str) -> list[str]:
    """Return every FTS5 virtual table under ``namespace``.

    Return every FTS5 virtual table under ``namespace`` (excludes shadows
    — dropping the virtual table cascades to shadows automatically)."""
    escaped = namespace.replace("_", "\\_")
    rows = conn.execute(
        "SELECT name FROM sqlite_master WHERE type='table' "
        "  AND name LIKE ? ESCAPE '\\' "
        "  AND sql LIKE 'CREATE VIRTUAL TABLE%' "
        "ORDER BY name",
        (escaped + "\\_%",),
    ).fetchall()
    return [r[0] for r in rows]


def _collect_triggers(conn: sqlite3.Connection, namespace: str) -> list[str]:
    """Return trigger names that begin with ``{namespace}_``."""
    escaped = namespace.replace("_", "\\_")
    rows = conn.execute(
        "SELECT name FROM sqlite_master WHERE type='trigger' AND name LIKE ? ESCAPE '\\' ORDER BY name",
        (escaped + "\\_%",),
    ).fetchall()
    return [r[0] for r in rows]


# Map of base table → FTS5 virtual table spec used to reconstruct the
# index. Mirrors ``_init_schema`` in :mod:`octop_memory.storage.backends.sqlite`.
# Updating either side without the other will cause silent FTS drift, so
# CI's e2e test (M5.8 — deferred per D46-C, but worth adding back when
# we ship multi-backend) should round-trip a rename + search query.
_FTS_SPECS: tuple[tuple[str, str, str, tuple[str, ...]], ...] = (
    # (base_table_suffix, trigger_prefix, fts_table_suffix, (column1, ...)).
    # trigger_prefix MUST match _init_schema's trigger names ({ns}_memory_ai
    # etc.) — a different name here would survive the next _init_schema's
    # CREATE TRIGGER IF NOT EXISTS and double-insert into FTS.
    ("memory_nodes", "memory", "memory_fts", ("content", "topic")),
    ("messages", "messages", "messages_fts", ("content",)),
    ("raw_events", "raw_events", "raw_events_fts", ("content",)),
    ("candidates", "candidates", "candidates_fts", ("title", "assertion", "verbatim_quote")),
    ("atoms", "atoms", "atoms_fts", ("assertion", "verbatim_quote", "search_terms")),
)


def _rebuild_fts_and_triggers(conn: sqlite3.Connection, namespace: str) -> None:
    """Recreate FTS5 tables and sync triggers for ``namespace``.

    Recreate FTS5 tables + AFTER INSERT/UPDATE/DELETE triggers under
    ``namespace`` and repopulate the FTS index from the base table.

    Both the trigger bodies and the repopulation pass run every value
    through ``hm_cjk_seg`` so the rebuilt index keeps the per-character
    CJK segmentation (see :mod:`octop_memory.storage.backends.fts_text`).
    """
    register_fts_functions(conn)
    for base_suffix, trigger_prefix, fts_suffix, columns in _FTS_SPECS:
        base = f"{namespace}_{base_suffix}"
        fts = f"{namespace}_{fts_suffix}"

        # Skip if the base table doesn't exist (the suffix list covers
        # M0/M1 tables that may be absent in newer namespaces).
        existing = conn.execute(
            "SELECT 1 FROM sqlite_master WHERE type='table' AND name=?",
            (base,),
        ).fetchone()
        if not existing:
            continue

        col_list = ", ".join(columns)
        new_vals = ", ".join(f"hm_cjk_seg(new.{c})" for c in columns)
        old_vals = ", ".join(f"hm_cjk_seg(old.{c})" for c in columns)
        conn.execute(
            f'CREATE VIRTUAL TABLE "{fts}" USING fts5('
            f"{col_list}, content='{base}', content_rowid='rowid', tokenize='unicode61')"
        )

        # AFTER INSERT trigger
        conn.execute(
            f'CREATE TRIGGER "{namespace}_{trigger_prefix}_ai" AFTER INSERT ON "{base}" BEGIN '
            f'  INSERT INTO "{fts}"(rowid, {col_list}) VALUES (new.rowid, {new_vals}); '
            f"END"
        )

        # AFTER DELETE trigger uses the FTS5 'delete' sentinel column
        # whose name MUST equal the FTS table name — recreated under
        # the new namespace so it stays consistent.
        conn.execute(
            f'CREATE TRIGGER "{namespace}_{trigger_prefix}_ad" AFTER DELETE ON "{base}" BEGIN '
            f'  INSERT INTO "{fts}"({fts}, rowid, {col_list}) '
            f"  VALUES ('delete', old.rowid, {old_vals}); "
            f"END"
        )

        # AFTER UPDATE trigger only emitted for tables that need it.
        # Memory_nodes / candidates / atoms have UPDATE triggers in
        # _init_schema; raw_events / messages do not (immutable).
        if base_suffix not in ("raw_events", "messages"):
            conn.execute(
                f'CREATE TRIGGER "{namespace}_{trigger_prefix}_au" AFTER UPDATE ON "{base}" BEGIN '
                f'  INSERT INTO "{fts}"({fts}, rowid, {col_list}) '
                f"  VALUES ('delete', old.rowid, {old_vals}); "
                f'  INSERT INTO "{fts}"(rowid, {col_list}) '
                f"  VALUES (new.rowid, {new_vals}); "
                f"END"
            )

        # Repopulate FTS from the base table.
        col_select = ", ".join(f"hm_cjk_seg({c})" for c in columns)
        conn.execute(f'INSERT INTO "{fts}"(rowid, {col_list}) SELECT rowid, {col_select} FROM "{base}"')


