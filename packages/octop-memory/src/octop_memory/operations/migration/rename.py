def plan_rename(
    db_path: str | Path,
    *,
    src_namespace: str,
    dst_namespace: str,
    mode: RenameMode = "rename",
) -> RenamePlan:
    """Plan a rename without touching anything; cheap and read-only."""
    if not src_namespace:
        raise ValueError("src_namespace cannot be empty")
    if not dst_namespace:
        raise ValueError("dst_namespace cannot be empty")
    if src_namespace == dst_namespace:
        raise ValueError("src and dst namespaces are identical; nothing to do")

    path = Path(db_path).expanduser()
    if not path.exists():
        raise FileNotFoundError(f"database file not found: {path}")

    plan = RenamePlan(db_path=path, src_namespace=src_namespace, dst_namespace=dst_namespace, mode=mode)

    # Use read-only connection so we can't accidentally mutate during planning.
    uri = f"file:{path}?mode=ro"
    conn = sqlite3.connect(uri, uri=True)
    try:
        all_src_tables = _list_namespace_tables(conn, src_namespace)
        # Filter out FTS shadow tables — renaming the parent FTS5 virtual
        # table cascades to its shadows automatically, and direct
        # ALTER TABLE on a shadow is rejected by SQLite.
        src_tables = [t for t in all_src_tables if not _is_fts_shadow(t)]
        if not src_tables:
            return plan

        existing_dst_tables = {t for t in _list_namespace_tables(conn, dst_namespace) if not _is_fts_shadow(t)}

        for table in src_tables:
            suffix = table[len(src_namespace) :]  # includes leading underscore
            dst_table = f"{dst_namespace}{suffix}"
            if dst_table in existing_dst_tables:
                plan.conflicts.append(dst_table)
            is_fts = _is_fts_virtual(table)
            row_count = -1 if is_fts else _table_row_count(conn, table)
            plan.steps.append(
                TablePlan(
                    src_table=table,
                    dst_table=dst_table,
                    row_count=row_count,
                    is_fts_shadow=is_fts,  # repurposed: True = FTS virtual (skip COUNT)
                )
            )
    finally:
        conn.close()

    return plan


def apply_rename(plan: RenamePlan, *, allow_overwrite: bool = False) -> int:
    """Execute the plan. Returns number of tables affected.

    Atomic: wraps the entire operation in a single SQLite transaction.
    On any error all renames roll back.

    After the rename, FTS5 virtual tables and AFTER INSERT/UPDATE/DELETE
    triggers are dropped and rebuilt from the renamed base tables.
    SQLite's ``ALTER TABLE RENAME TO`` rewrites trigger BODIES that
    reference the renamed table, but it can't fix:

    1. FTS5 ``content=...`` virtual-table parameters (which still
       point at the OLD base table name).
    2. FTS5 magic "delete" sentinel column in AFTER DELETE triggers
       (the column NAME is the FTS table itself; rename leaves it stale).

    So we drop every FTS / trigger pair under the source namespace,
    let the next ``Memory(namespace=dst)`` open re-create them via
    ``_init_schema``, then repopulate FTS via ``INSERT INTO fts(rowid,
    ...) SELECT rowid, ... FROM base``.

    Args:
        plan: result of :func:`plan_rename`. Pass directly; do not
            mutate.
        allow_overwrite: if ``True``, drops conflicting destination
            tables before renaming. Required when ``plan.has_conflicts``.
    """
    if not plan.steps:
        return 0
    if plan.has_conflicts and not allow_overwrite:
        raise ValueError(
            f"destination tables already exist: {plan.conflicts!r}; pass allow_overwrite=True to drop them first"
        )

    conn = sqlite3.connect(str(plan.db_path))
    committed = False
    try:
        # Disable autocommit; we manage the txn manually so partial
        # rename never leaves the DB half-renamed.
        conn.execute("BEGIN IMMEDIATE")

        if allow_overwrite:
            for conflict in plan.conflicts:
                conn.execute(f'DROP TABLE IF EXISTS "{conflict}"')

        if plan.mode == "rename":
            # Phase 1: drop ALL FTS virtual tables + triggers under the
            # source namespace BEFORE renaming the base tables. We'll
            # rebuild them under the destination namespace at the end.
            fts_tables = _collect_fts_tables(conn, plan.src_namespace)
            triggers = _collect_triggers(conn, plan.src_namespace)
            for trig in triggers:
                conn.execute(f'DROP TRIGGER IF EXISTS "{trig}"')
            for fts in fts_tables:
                conn.execute(f'DROP TABLE IF EXISTS "{fts}"')

            # Phase 2: rename remaining base tables. Skip the FTS tables
            # we just dropped (they're already gone).
            for step in plan.steps:
                if step.is_fts_shadow:  # marker: this is the FTS virtual table itself
                    continue
                # Some indices may have been auto-renamed; ALTER on a
                # table that no longer exists is a no-op error we
                # tolerate via IF EXISTS-style guard.
                conn.execute(f'ALTER TABLE "{step.src_table}" RENAME TO "{step.dst_table}"')

            # Phase 3: rebuild FTS virtual tables + triggers under the
            # destination namespace, then repopulate FTS from the
            # renamed base tables.
            _rebuild_fts_and_triggers(conn, plan.dst_namespace)
        elif plan.mode == "copy":
            # CREATE TABLE dst AS SELECT * FROM src — preserves rows
            # but loses indexes / triggers / FTS5 contentless table
            # specifics. The caller MUST instantiate a fresh
            # ``Memory(namespace=dst)`` afterwards so the
            # ``_init_schema`` recreates indexes + triggers + FTS
            # virtual tables. For FTS virtual tables we skip — the
            # new namespace's _init_schema will rebuild them and the
            # AFTER INSERT triggers will re-populate from the copied
            # base tables.
            for step in plan.steps:
                if step.is_fts_shadow:  # actually "is FTS virtual" — see plan_rename
                    continue
                conn.execute(f'CREATE TABLE "{step.dst_table}" AS SELECT * FROM "{step.src_table}"')
            # The copied {dst}_meta carries the source's fts_text_version,
            # which would make the destination's first _init_schema skip
            # the FTS rebuild and leave the copied namespace unsearchable.
            # Clear the marker so the rebuild runs against the copied rows.
            meta_table = f"{plan.dst_namespace}_meta"
            exists = conn.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (meta_table,)).fetchone()
            if exists:
                conn.execute(f'DELETE FROM "{meta_table}" WHERE key = ?', ("fts_text_version",))
        else:
            raise ValueError(f"unknown mode: {plan.mode!r}")

        conn.commit()
        committed = True
    finally:
        try:
            if not committed:
                conn.rollback()
        finally:
            conn.close()

    return len(plan.steps)


