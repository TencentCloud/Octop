-- Schema v26: HITL pending store persistence.
-- Replaces the in-process dict store with a PostgreSQL-backed table so
-- pending records survive restarts, multi-instance deployments, and
-- enable transactional idempotency for structured form submissions.

CREATE TABLE IF NOT EXISTS hitl_pending_records (
  id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pending_id                TEXT NOT NULL UNIQUE,
  thread_id                 TEXT NOT NULL,
  agent_id                  TEXT NOT NULL,
  user_id                   TEXT NOT NULL,
  session_key               TEXT NOT NULL,
  channel_type              TEXT NOT NULL DEFAULT '',
  action_requests           JSONB NOT NULL DEFAULT '[]'::jsonb,
  review_configs            JSONB,
  status                    TEXT NOT NULL DEFAULT 'pending',
  ask_question_index        INTEGER NOT NULL DEFAULT 0,
  ask_answers               JSONB,
  resume_agent_id           TEXT,
  resume_thread_id          TEXT,
  form_context              JSONB,
  consumed_submission_ids   JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at                DOUBLE PRECISION NOT NULL,
  updated_at                DOUBLE PRECISION NOT NULL DEFAULT 0
);

-- Lookup by pending_id (primary key already covers exact match).

-- Resolve pending records for a session (most recent first).
CREATE INDEX IF NOT EXISTS idx_hpr_session_agent_created
  ON hitl_pending_records(session_key, agent_id, created_at DESC);

-- Resolve pending for a thread (direct or via resume_thread_id).
CREATE INDEX IF NOT EXISTS idx_hpr_thread_id
  ON hitl_pending_records(thread_id);
CREATE INDEX IF NOT EXISTS idx_hpr_resume_thread_id
  ON hitl_pending_records(resume_thread_id);

-- Cancel by form_id (form_context->>'form_id').
CREATE INDEX IF NOT EXISTS idx_hpr_form_id
  ON hitl_pending_records((form_context->>'form_id'))
  WHERE form_context IS NOT NULL;

-- List pending thread IDs for an agent/user.
CREATE INDEX IF NOT EXISTS idx_hpr_agent_user_status
  ON hitl_pending_records(agent_id, user_id, status);

-- GC / expiration queries.
CREATE INDEX IF NOT EXISTS idx_hpr_status_created
  ON hitl_pending_records(status, created_at);

-- Slot reuse detection (same session + thread + resume_agent).
CREATE INDEX IF NOT EXISTS idx_hpr_slot
  ON hitl_pending_records(session_key, thread_id, resume_agent_id);

UPDATE _schema_version SET version = 26;
