-- Schema v25: GitHub-style MFA (TOTP, WebAuthn/passkeys, recovery codes) and
-- DB-backed auth challenges.

ALTER TABLE users ADD COLUMN IF NOT EXISTS mfa_version INTEGER NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS mfa_failed_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS mfa_locked_until INTEGER NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS user_totp (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id             BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  secret_enc          BYTEA NOT NULL,
  verified_at         BIGINT,
  pending_expires_at  BIGINT,
  last_used_step      BIGINT,
  created_at          BIGINT NOT NULL,
  updated_at          BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS user_webauthn_credentials (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  credential_id       TEXT NOT NULL UNIQUE,
  user_id             BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  public_key          BYTEA NOT NULL,
  user_handle         TEXT NOT NULL,
  rp_id               TEXT NOT NULL,
  aaguid              TEXT,
  sign_count          BIGINT NOT NULL DEFAULT 0,
  backup_eligible     INTEGER NOT NULL DEFAULT 0,
  backup_state        INTEGER NOT NULL DEFAULT 0,
  name                TEXT,
  transports_json     TEXT NOT NULL DEFAULT '[]',
  created_at          BIGINT NOT NULL,
  last_used_at        BIGINT
);

CREATE INDEX IF NOT EXISTS idx_user_webauthn_user_id
  ON user_webauthn_credentials(user_id);

CREATE TABLE IF NOT EXISTS user_recovery_codes (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id             BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  code_hash           TEXT NOT NULL,
  used_at             BIGINT,
  created_at          BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_user_recovery_codes_user_id
  ON user_recovery_codes(user_id);

CREATE TABLE IF NOT EXISTS auth_challenges (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  challenge           TEXT UNIQUE,
  jti                 TEXT UNIQUE,
  kind                TEXT NOT NULL,
  user_id             BIGINT REFERENCES users(id) ON DELETE CASCADE,
  attempts            INTEGER NOT NULL DEFAULT 0,
  expires_at          BIGINT NOT NULL,
  consumed_at         BIGINT,
  created_at          BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_auth_challenges_expires_at
  ON auth_challenges(expires_at);

UPDATE _schema_version SET version = 25;
