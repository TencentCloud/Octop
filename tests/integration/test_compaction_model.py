@pytest.mark.asyncio
@pytest.mark.parametrize("primary_fails", [False, True])
async def test_dashboard_compact_uses_conversation_or_reports_real_backup(
    env_with_main_agent,
    tmp_path,
    monkeypatch,
    primary_fails,
):
    client, server, admin, aid = env_with_main_agent
    await create_provider(
        client,
        admin,
        name="compact",
        base_url="https://compact.invalid/v1",
        models=[{"id": name, "enabled": True} for name in ("chat", "small")],
    )
    manager = server.app_runtime.agent_registry
    user_id = manager.get_row(aid).user_id
    user = SimpleNamespace(id=user_id, is_admin=True, locale="en")
    if primary_fails:
        r = await client.put(
            "/api/providers/compaction-model", headers=admin, json={"model": "compact/small"}
        )
        assert r.status_code == 200
    frame = UserTurnWsFrame(type="user_turn", model="compact/chat", text="/compact")
    turn = frame.to_turn_body()
    prepared = await prepare_dashboard_turn(server, agent_id=aid, user=user, turn=turn)
    inbound = build_dashboard_inbound(
        agent_id=aid, user_id=user_id, prepared=prepared, turn=turn, ws_connection_id="test"
    )
    services = server.services
    ctx = build_slash_ctx(
        agent_id=aid,
        user_id=user_id,
        channel_type="dashboard",
        session_key=prepared.session_key,
        metadata=inbound.metadata,
        thread_registry=server.app_runtime.gateway.thread_registry,
        agent_manager=manager,
        agent_repo=services.agent_repo,
        user_repo=services.user_repo,
        user_locale="en",
    )

    calls = []

    class BillingError(RuntimeError):
        status_code = 402

    class SummaryModel(FakeListChatModel):
        ref: str

        def with_retry(self, **kwargs):
            return self

        def _call(self, *args, **kwargs):
            calls.append(self.ref)
            if self.ref == "compact/small":
                raise BillingError("insufficient balance")
            return "Summary from the conversation model"

    harness = object.__new__(HarnessAgent)
    harness._graph = MagicMock()
    messages = [
        m
        for n in range(12)
        for m in (HumanMessage(content=f"question {n}"), AIMessage(content=f"answer {n}"))
    ]
    harness._graph.aget_state = AsyncMock(
        return_value=SimpleNamespace(values={"messages": messages})
    )
    harness._graph.aupdate_state = AsyncMock()
    harness._summarization_mw = None
    harness._context_usage_mw = None
    harness._backend = resolve_backend(
        {"type": "filesystem", "root_dir": str(tmp_path), "virtual_mode": True},
        workspace_dir=tmp_path,
    )
    harness._model_factory = MagicMock()
    harness._model_factory.get_chat_model.side_effect = lambda ref: SummaryModel(
        responses=["unused"], ref=ref, profile={"max_input_tokens": 128_000}
    )
    monkeypatch.setattr(manager, "get_agent", lambda _aid: harness)
    handled, lines, _actions = await try_handle_slash(
        turn.text, dispatcher=build_default_dispatcher(), ctx=ctx
    )
    assert handled
    assert calls == (["compact/small", "compact/chat"] if primary_fails else ["compact/chat"])
    harness._graph.aupdate_state.assert_awaited_once()
    summary = harness._graph.aupdate_state.await_args.args[1]["_summarization_event"][
        "summary_message"
    ]
    assert "Summary from the conversation model" in str(summary.content)
    if primary_fails:
        text = "\n".join(lines)
        assert "Summary generated by compact/chat." in text
        assert "compact/small failed" in text and "HTTP 402" in text
        assert "/admin/models?tab=chat#compact-model" in text


@pytest.mark.asyncio
async def test_compact_model_settings_and_access(env_with_main_agent):
    client, _server, admin, aid = env_with_main_agent
    url = "/api/providers/compaction-model"
    await create_provider(
        client,
        admin,
        name="compact",
        base_url="https://compact.invalid/v1",
        models=[{"id": "small", "enabled": True}],
    )
    regular = await create_user(client, admin, username="reader")
    assert (
        await client.put(url, headers=regular, json={"model": "compact/small"})
    ).status_code == 403
    assert (await client.put(url, headers=admin, json={"model": "missing/x"})).status_code == 400
    assert (
        await client.put(url, headers=admin, json={"model": "compact/small"})
    ).status_code == 200
    assert (await client.get(url, headers=admin)).json()["model"] == "compact/small"
    for value in ("compact/small", "session", None):
        reply = await client.patch(
            f"/api/agents/{aid}",
            headers=admin,
            json={"compaction": {"model": value, "enabled": False}},
        )
        assert reply.status_code == 200, reply.text
        cfg = (await client.get(f"/api/agents/{aid}", headers=admin)).json()["compaction"]
        assert cfg.get("model") == value
        assert cfg["enabled"] is False
    assert (await client.put(url, headers=admin, json={"model": None})).status_code == 200
